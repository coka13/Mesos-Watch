// Rebuilds dist/hud-glyphs.mjs: the status bar's digit shapes, averaged per capture from real game screenshots whose text is known.
//   node scripts/make-hud-glyphs.mjs            write the templates
//   node scripts/make-hud-glyphs.mjs --check    also report leave-one-capture-out accuracy
// Add captures to SOURCES to cover more digits or display settings. Every template stays traceable to these screenshots.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {Jimp} from 'jimp';

const file=new URL('../dist/hud-glyphs.mjs',import.meta.url);
// glyphCells and glyphImage do not use the templates, so an empty set is enough to build the first one.
fs.writeFileSync(file,'export const GLYPH_W=8,GLYPH_H=12,GLYPHS={};\n');
const {findStatusBar,textAreas,glyphCells,glyphImage,isSeparator,readGlyphs,parseExp,expFill}=await import('../dist/hud.mjs');
const {GLYPH_W,GLYPH_H}=await import('../dist/hud-glyphs.mjs');

export const SOURCES=[
 {file:'store-empty-sold',exp:'93,965 76,54%',hp:'851/851',mp:'1621/1621'},
 {file:'store-fm-room',exp:'49,732 40,51%',hp:'851/851',mp:'1621/1621'},
 {file:'store-fm-channel',exp:'49,732 40,51%',hp:'851/851',mp:'1621/1621'},
];
const SCALES=[1,1.25,1.5,2];
const load=async(s,scale)=>{const i=await Jimp.read(fileURLToPath(new URL('../tests/fixtures/'+s.file+'.png',import.meta.url)));if(scale!==1)i.resize({w:Math.round(i.bitmap.width*scale),h:Math.round(i.bitmap.height*scale)});return{data:i.bitmap.data,width:i.bitmap.width,height:i.bitmap.height};};
// The characters a text area should hold, in order, without the small separators.
const chars=t=>[...t].filter(c=>c!==' '&&c!==','&&c!=='.');

async function samples(sources){
 const out={};let skipped=0;
 for(const s of sources)for(const scale of SCALES){
  const px=await load(s,scale),bar=findStatusBar(px);if(!bar){skipped++;continue;}
  const areas=textAreas(bar,px.width,px.height);
  for(const field of ['exp','hp','mp']){
   const page=glyphCells(px,areas[field],areas.advance),cells=page.cells.filter(c=>!isSeparator(page,c)),want=chars(s[field]);
   if(cells.length!==want.length){skipped++;continue;}
   cells.forEach((c,i)=>((out[want[i]]??={})[s.file]??=[]).push(glyphImage(page,c)));
  }
 }
 return{out,skipped};
}
const same=(a,b)=>!!a&&!!b&&a.exp===b.exp&&a.pct===b.pct;
const mean=list=>{const m=new Float32Array(GLYPH_W*GLYPH_H);for(const a of list)for(let i=0;i<m.length;i++)m[i]+=a[i]/list.length;return m;};
const templates=out=>Object.fromEntries(Object.entries(out).map(([k,v])=>[k,Object.values(v).map(mean)]));
const encode=a=>[...a].map(v=>Math.round(v*15).toString(16)).join('');

function write(t){
 const body=Object.entries(t).sort().map(([k,v])=>` ${JSON.stringify(k)}:${JSON.stringify(v.map(encode))},`).join('\n');
 fs.writeFileSync(file,`// Generated by scripts/make-hud-glyphs.mjs from real game captures (tests/fixtures). ${GLYPH_W}x${GLYPH_H} ink levels, 0-f, by row;
// one template per capture, because each capture's scaling blurs the font differently.
export const GLYPH_W=${GLYPH_W},GLYPH_H=${GLYPH_H};
const raw={
${body}
};
export const GLYPHS=Object.fromEntries(Object.entries(raw).map(([k,v])=>[k,v.map(t=>Float32Array.from(t,c=>parseInt(c,16)/15))]));
`);
}
const {out,skipped}=await samples(SOURCES),all=templates(out);
const missing=[...'0123456789/%'].filter(c=>!all[c]);if(missing.length)throw Error('No samples for '+missing.join(' '));
write(all);
console.log('Templates for',Object.keys(all).sort().join(' '),'from',Object.values(out).flatMap(Object.values).reduce((n,v)=>n+v.length,0),'glyphs;',skipped,'areas skipped');
if(process.argv.includes('--check')){
 let right=0,total=0,wrong=0;
 for(const held of SOURCES){
  const t=templates((await samples(SOURCES.filter(s=>s!==held))).out);
  for(const scale of [.8,...SCALES]){
   const px=await load(held,scale),bar=findStatusBar(px);
   if(!bar){console.log(held.file,scale,'no bar');total+=3;continue;}
   const a=textAreas(bar,px.width,px.height),fill=expFill(px,bar);
   for(const field of ['exp','hp','mp']){
    const got=readGlyphs(px,a[field],a.advance,t).text,parsed=field==='exp'?parseExp(got,fill):null,ok=field==='exp'?same(parsed,parseExp(held.exp)):got===held[field];
    total++;right+=ok?1:0;if(!ok){if(field!=='exp'||parsed)wrong++;console.log(held.file,'x'+scale,field,JSON.stringify(got),'want',held[field]);}
   }
  }
 }
 console.log(`Held-out reads exact: ${right}/${total}; wrong values among the misses: ${wrong}`);
}
